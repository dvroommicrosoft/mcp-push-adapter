#!/usr/bin/env node
// Install the push-adapter Copilot extension as a stub that imports this checkout.
//   node scripts/install-copilot.mjs [--scope user|project] [--project DIR] [--uninstall]
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const { values: opts } = parseArgs({
  options: {
    scope: { type: "string", default: "user" },
    project: { type: "string", default: process.cwd() },
    uninstall: { type: "boolean", default: false },
  },
});
const base = {
  user: join(process.env.COPILOT_HOME ?? join(homedir(), ".copilot"), "extensions"),
  project: join(resolve(opts.project), ".github", "extensions"),
}[opts.scope];
if (!base) {
  console.error(`unknown --scope ${opts.scope} (use user or project)`);
  process.exit(2);
}
const dir = join(base, "push-adapter");
if (opts.uninstall) {
  rmSync(dir, { recursive: true, force: true });
  console.log(`removed ${dir}`);
} else {
  const target = pathToFileURL(resolve(import.meta.dirname, "../copilot-extension/extension.mjs")).href;
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "extension.mjs"), `// push-adapter: generated by install-copilot.mjs\nimport ${JSON.stringify(target)};\n`);
  console.log(`installed ${dir}/extension.mjs -> ${target}`);
  console.log("Reload extensions (/clear or restart Copilot), then add a push-adapter.json (see README).");
}
